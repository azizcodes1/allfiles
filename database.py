def get_user_generations(user_id):
    """Retrieve all images generated by a specific user."""
    conn = get_conn()
    cur = conn.cursor()
    cur.execute("SELECT prompt, image_url, timestamp, is_public, id FROM generations WHERE user_id = %s ORDER BY timestamp DESC", (user_id,))
    res = cur.fetchall()
    cur.close()
    conn.close()
    return res

