def mark_transaction_paid(comment_id):
    """Update transaction status and grant premium."""
    conn = get_conn()
    cur = conn.cursor()
    cur.execute("SELECT user_id FROM pending_transactions WHERE comment_id = %s", (comment_id,))
    res = cur.fetchone()
    if res:
        user_id = res[0]
        cur.execute("UPDATE pending_transactions SET status = 'paid' WHERE comment_id = %s", (comment_id,))
        cur.execute("UPDATE users SET is_premium = true WHERE user_id = %s", (user_id,))
        conn.commit()
        cur.close()
        conn.close()
        return user_id
    cur.close()
    conn.close()
    return None

